const assert = require('node:assert/strict');
const { compare } = require('./assets/holding-period-cashflow.js');
const base = { years: 3, fee: 3000, exitTax: 10000, discount: 0, benefits: [20000, -2000, -2000] };
const nominal = compare(base);
assert.equal(nominal.nominal, 3000);
assert.equal(nominal.presentValue, 3000);
assert.equal(nominal.rows[0].saleTax, 0);
assert.equal(nominal.rows[2].saleTax, 10000);
assert.equal(nominal.rows[2].net, -12000);
assert.ok(Math.abs(compare({ ...base, discount: 5 }).presentValue - 3867.5089083252333) < 1e-8);
assert.equal(compare({ years: 1, fee: 3000, exitTax: 0, discount: 0, benefits: [0] }).presentValue, -3000);
assert.equal(compare({ years: 1, fee: 0, exitTax: 1000, discount: 0, benefits: [-500] }).nominal, -1500);
for (const x of [{ years: 0 }, { years: 2.5 }, { years: 41 }, { benefits: [20000] }, { benefits: [Infinity, 0, 0] }, { fee: NaN }, { exitTax: -1 }, { discount: -1 }, { discount: 101 }]) assert.throws(() => compare({ ...base, ...x }));
console.log('Holding-period arithmetic and invalid-input checks passed.');
